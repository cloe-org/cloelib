"""
Characterization ("golden") tests for `ShearTracer`/`PositionsTracer`/
`CMBLensingTracer`'s `get_window`/`get_Cl` output.

These pin `get_window`/`get_Cl` outputs for `ShearTracer` (with a non-zero
NLA intrinsic-alignment contribution), `PositionsTracer` (all three
`galaxy_bias_model` variants), and `CMBLensingTracer` against known-good
reference values. Their purpose is to make any accidental numeric drift in
this code fail loudly here first. They intentionally do not re-derive the
physics or assert anything about *correctness* - only that today's exact
output is preserved (in particular: they guarantee the Contribution-based
architecture in `cloelib.observables.photo` - `LensingContribution`,
`NLAContribution`, `GalaxyBiasContribution`,
`MagnificationContribution` composed via `get_contributions()` - reproduces
the same output as directly-summed window methods, for every default
(non-TATT) configuration).

Reference values live in `tests/fixtures/photo_tracers_baseline.npz`,
generated by `tests/fixtures/generate_photo_tracers_baseline.py` (not
collected by pytest; regenerate only if a change is *intended* to alter
these outputs). Note: `tests/fixtures/` is used rather than a `data/`-named
directory because this repo's `.gitignore` excludes `*/data/*` repo-wide.
"""

from pathlib import Path

import numpy as np
import pytest

from cloelib.cosmology.camb_cosmology import (
    CAMBBackground,
    CAMBNonLinearPerturbations,
)
from cloelib.cosmology.jax_cosmology import JAXBackground, JAXLinearPerturbations
from cloelib.observables.cmb import CMBLensingTracer
from cloelib.observables.photo import PositionsTracer, ShearTracer
from cloelib.summary_statistics.angular_two_point import AngularTwoPoint

BASELINE_PATH = Path(__file__).parent / "fixtures" / "photo_tracers_baseline.npz"


@pytest.fixture(scope="module")
def baseline():
    """Reference arrays captured from the pre-refactor codebase."""
    with np.load(BASELINE_PATH) as data:
        return {k: data[k] for k in data.files}


